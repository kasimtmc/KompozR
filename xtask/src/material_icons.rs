//! `cargo xtask material-icons [--check]`: the material icons (Compose's `androidx.compose.material.icons`, each a
//! Kotlin file building an `ImageVector` with `materialIcon { materialPath { moveTo(…) … } }`) converted to data
//! for their crate: `crates/kompoz-material-icons-core/` (material-icons-core 1.7.8's Filled, Outlined, Rounded,
//! Sharp, TwoTone and AutoMirrored themes). Each theme is a data file (`data/<theme>.txt`: an icon a line, its name
//! and its paths — fill alpha, stroke alpha, fill type and SVG path data, the builder's calls written as the path
//! commands they add) and a Rust file (`src/generated/<theme>.rs`) listing the icons with where their line is,
//! which the crate's `icons!` makes functions of (`Icons::Filled::Add()`), each building its vector once, when first
//! asked for.
//!
//! The extended icons (material-icons-extended, WP9) are the same jar layout: `convert_jar` takes a jar and an output
//! crate.
//!
//! It reads the sources jars from Gradle's cache; `--check` converts and compares where the jar is, and says it
//! skipped where it isn't (CI).

use crate::jar::Jar;
use std::collections::BTreeMap;
use std::fmt::Write as _;
use std::path::Path;

const GROUP: &str = "androidx.compose.material";
const VERSION: &str = "1.7.8";
const PREFIX: &str = "commonMain/androidx/compose/material/icons/";

/// The themes: their directory in the jar, their Kotlin name, the data file's and the module's name.
const THEMES: [(&str, &str, &str); 10] = [
    ("filled/", "Filled", "filled"),
    ("outlined/", "Outlined", "outlined"),
    ("rounded/", "Rounded", "rounded"),
    ("sharp/", "Sharp", "sharp"),
    ("twotone/", "TwoTone", "two_tone"),
    ("automirrored/filled/", "AutoMirrored.Filled", "auto_mirrored_filled"),
    ("automirrored/outlined/", "AutoMirrored.Outlined", "auto_mirrored_outlined"),
    ("automirrored/rounded/", "AutoMirrored.Rounded", "auto_mirrored_rounded"),
    ("automirrored/sharp/", "AutoMirrored.Sharp", "auto_mirrored_sharp"),
    ("automirrored/twotone/", "AutoMirrored.TwoTone", "auto_mirrored_two_tone"),
];

pub fn run(root: &Path, check: bool) -> Result<(), String> {
    let artifact = "material-icons-core-android";
    let Some(jar) = Jar::find(GROUP, artifact, VERSION, "-sources.jar") else {
        if check {
            println!("material-icons: skipped (no {GROUP}:{artifact}:{VERSION} sources jar in Gradle's cache)");
            return Ok(());
        }
        return Err(format!("no {GROUP}:{artifact}:{VERSION} sources jar in Gradle's cache"));
    };
    convert_jar(root, &Jar::open(&jar)?, "crates/kompoz-material-icons-core", "material-icons-core", check)
}

/// Converts the icons of `jar` into the crate at `out` (its `data/` and `src/generated/`).
pub fn convert_jar(root: &Path, jar: &Jar, out: &str, library: &str, check: bool) -> Result<(), String> {
    let mut data = BTreeMap::new();
    let mut generated = BTreeMap::new();
    for (dir, theme, module) in THEMES {
        let names: Vec<String> = jar
            .names(&format!("{PREFIX}{dir}"), ".kt")
            .into_iter()
            .filter(|n| !n[PREFIX.len() + dir.len()..].contains('/'))
            .collect();
        if names.is_empty() {
            continue;
        }
        let mut lines = String::new();
        let mut entries = Vec::new();
        for name in &names {
            let icon = parse_icon(&jar.text(name)?, theme).map_err(|e| format!("{name}: {e}"))?;
            let start = lines.len();
            lines.push_str(&icon.line);
            let end = lines.len();
            lines.push('\n');
            entries.push((icon.name, start, end, icon.deprecated));
        }
        data.insert(format!("{module}.txt"), lines);
        let mut s = format!(
            "//! Generated by `cargo xtask material-icons` from {library} {VERSION}'s Icons.{theme} (data/{module}.txt): \
             do not edit.\n\ncrate::icons! {{\n    \"{theme}\", \"../../data/{module}.txt\";\n"
        );
        for (name, start, end, deprecated) in &entries {
            match deprecated {
                Some(note) => {
                    let _ = writeln!(s, "    #[deprecated(note = \"{note}\")] {name} {start} {end},");
                }
                None => {
                    let _ = writeln!(s, "    {name} {start} {end},");
                }
            }
        }
        s.push_str("}\n");
        generated.insert(format!("{module}.rs"), s);
    }
    crate::write_generated(root, &format!("{out}/data"), &data, check, "material-icons")?;
    crate::write_generated(root, &format!("{out}/src/generated"), &generated, check, "material-icons")
}

struct Icon {
    name: String,
    /// Its data line: `Name|fillAlpha,strokeAlpha,N|E:pathData|…`.
    line: String,
    /// A deprecated one's note (Compose's `@Deprecated("…")`).
    deprecated: Option<String>,
}

fn parse_icon(text: &str, theme: &str) -> Result<Icon, String> {
    let deprecated = text.find("@Deprecated(").and_then(|at| {
        let rest = &text[at..];
        let open = rest.find('"')?;
        let close = rest[open + 1..].find('"')?;
        Some(rest[open + 1..open + 1 + close].to_string())
    });
    let decl = format!("val Icons.{theme}.");
    let at = text.find(&decl).ok_or("no icon declared")?;
    let name: String = text[at + decl.len()..].chars().take_while(|c| c.is_ascii_alphanumeric() || *c == '_').collect();
    let icon_call = text.find("materialIcon(").ok_or("no materialIcon(…)")?;
    let args = &text[icon_call..text[icon_call..].find(')').map(|e| icon_call + e).ok_or("materialIcon's )")?];
    let args = args.split_whitespace().collect::<Vec<_>>().join(" ");
    if !args.contains(&format!("name = \"{theme}.{name}\"")) {
        return Err(format!("materialIcon's name isn't {theme}.{name}"));
    }
    let auto_mirror = args.contains("autoMirror = true");
    if auto_mirror != theme.starts_with("AutoMirrored.") {
        return Err("autoMirror where the theme isn't AutoMirrored, or the reverse".into());
    }
    let mut line = name.clone();
    let mut rest = &text[icon_call..];
    let mut paths = 0;
    while let Some(p) = rest.find("materialPath") {
        rest = &rest[p + "materialPath".len()..];
        let (args, body_at) = match rest.strip_prefix('(') {
            Some(r) => {
                let close = r.find(')').ok_or("materialPath's )")?;
                (&r[..close], close + 2)
            }
            None => ("", 0),
        };
        let mut fill_alpha = "1".to_string();
        let mut stroke_alpha = "1".to_string();
        let mut fill_type = "N";
        for a in args.split(',').map(str::trim).filter(|a| !a.is_empty()) {
            let (k, v) = a.split_once('=').ok_or(format!("materialPath's argument {a}"))?;
            let v = v.trim();
            match k.trim() {
                "fillAlpha" => fill_alpha = number(v)?,
                "strokeAlpha" => stroke_alpha = number(v)?,
                "pathFillType" => {
                    fill_type = match v {
                        "PathFillType.EvenOdd" => "E",
                        "PathFillType.NonZero" => "N",
                        other => return Err(format!("a fill type {other}")),
                    }
                }
                other => return Err(format!("materialPath's argument {other}")),
            }
        }
        rest = &rest[body_at..];
        let open = rest.find('{').ok_or("materialPath without a block")?;
        let close = rest[open..].find('}').ok_or("materialPath's block's }")? + open;
        let body = &rest[open + 1..close];
        let _ = write!(line, "|{fill_alpha},{stroke_alpha},{fill_type}:{}", path_data(body)?);
        paths += 1;
        rest = &rest[close..];
    }
    if paths == 0 {
        return Err("no paths".into());
    }
    Ok(Icon { name, line, deprecated })
}

/// A path builder's calls as SVG path data.
fn path_data(body: &str) -> Result<String, String> {
    let mut d = String::new();
    for call in body.lines().map(str::trim).filter(|l| !l.is_empty()) {
        let open = call.find('(').ok_or(format!("a call {call}"))?;
        let name = &call[..open];
        let args: Vec<&str> = call[open + 1..call.rfind(')').ok_or(format!("a call {call}"))?]
            .split(',')
            .map(str::trim)
            .filter(|a| !a.is_empty())
            .collect();
        let (command, arity) = match name {
            "moveTo" => ('M', 2),
            "moveToRelative" => ('m', 2),
            "lineTo" => ('L', 2),
            "lineToRelative" => ('l', 2),
            "horizontalLineTo" => ('H', 1),
            "horizontalLineToRelative" => ('h', 1),
            "verticalLineTo" => ('V', 1),
            "verticalLineToRelative" => ('v', 1),
            "curveTo" => ('C', 6),
            "curveToRelative" => ('c', 6),
            "reflectiveCurveTo" => ('S', 4),
            "reflectiveCurveToRelative" => ('s', 4),
            "quadTo" => ('Q', 4),
            "quadToRelative" => ('q', 4),
            "reflectiveQuadTo" => ('T', 2),
            "reflectiveQuadToRelative" => ('t', 2),
            "arcTo" => ('A', 7),
            "arcToRelative" => ('a', 7),
            "close" => ('Z', 0),
            other => return Err(format!("a path call {other}")),
        };
        if args.len() != arity {
            return Err(format!("{name} of {} arguments", args.len()));
        }
        d.push(command);
        let values: Vec<String> = args
            .iter()
            .map(|a| match *a {
                "true" => Ok("1".to_string()),
                "false" => Ok("0".to_string()),
                a => number(a),
            })
            .collect::<Result<_, _>>()?;
        d.push_str(&values.join(","));
    }
    Ok(d)
}

/// A Kotlin float literal as path data writes it (`19.0f` → `19`, `-0.5f` → `-0.5`).
fn number(a: &str) -> Result<String, String> {
    let n = a.trim().trim_end_matches('f');
    let v: f32 = n.parse().map_err(|_| format!("a number {a}"))?;
    // (as Rust prints an f32: the shortest text that reads back as the same float)
    Ok(format!("{v}"))
}
