//! The converter of Compose for desktop's translated texts that `material3-strings` and `adaptive-strings` share: a
//! skikoMain `internal/Strings.skiko.kt`'s ids (`actual val X = Strings(n)`) and its `l10n/*.kt` translations
//! (`internal fun Translations.tr() = mapOf(Strings.X to "…", …)`, `l10n/Translations.kt`'s locale tags) as Rust
//! data: `mod.rs` with the ids (`Strings::X`) and `translation_for(tag)`, a file per Kotlin file, each translation an
//! array of the texts by id.

use crate::jar::Jar;
use crate::material3_tokens::snake;
use std::collections::BTreeMap;
use std::fmt::Write as _;

/// What a task converts and how its generated files say where they come from.
pub struct Spec {
    /// The xtask's name (`material3-strings`).
    pub task: &'static str,
    /// The sources jar's `internal/Strings.skiko.kt`.
    pub strings: &'static str,
    /// The sources jar's `l10n/` directory (with its `/`).
    pub l10n: &'static str,
    /// Whose texts, for `mod.rs`'s first line (`material3's texts`).
    pub what: &'static str,
    /// Where `mod.rs`'s data comes from (`CMP material3-desktop 1.11.0-alpha07's skikoMain (…)`).
    pub module_source: &'static str,
    /// Where a translation file's data comes from (`Compose for desktop's material3 1.11.0-alpha07`).
    pub file_source: &'static str,
}

/// Converts `spec`'s texts from `jar`: the files of its `l10n/` directory (a file per Kotlin file, and `mod.rs`).
pub fn convert(jar: &Jar, spec: &Spec) -> Result<BTreeMap<String, String>, String> {
    // The ids: `actual val NavigationMenu = Strings(0)`.
    let mut ids: Vec<(String, usize)> = Vec::new();
    for line in jar.text(spec.strings)?.lines() {
        let l = line.trim();
        if let Some(rest) = l.strip_prefix("actual val ")
            && let Some((name, value)) = rest.split_once(" = Strings(")
        {
            let id: usize = value.trim_end_matches(')').parse().map_err(|_| format!("Strings id of {name}"))?;
            ids.push((name.trim().to_string(), id));
        }
    }
    ids.sort_by_key(|(_, id)| *id);
    if ids.iter().enumerate().any(|(k, (_, id))| k != *id) {
        return Err("Strings' ids aren't 0, 1, 2, …".into());
    }
    let count = ids.len();
    // The tags: `"en_AU" -> Translations.enAU()`.
    let mut tags: Vec<(String, String)> = Vec::new();
    for line in jar.text(&format!("{}Translations.kt", spec.l10n))?.lines() {
        let l = line.trim();
        if let Some(rest) = l.strip_prefix('"')
            && let Some((tag, call)) = rest.split_once("\" -> Translations.")
        {
            let function = call.trim_end_matches("()").trim_matches('`');
            tags.push((tag.to_string(), function.to_string()));
        }
    }
    // The translations: `internal fun Translations.tr() = mapOf(Strings.X to "…", …)`.
    let mut out = BTreeMap::new();
    let mut functions: BTreeMap<String, String> = BTreeMap::new();
    for name in jar.names(spec.l10n, ".kt") {
        let file = name.trim_start_matches(spec.l10n).trim_end_matches(".kt");
        if file == "Translations" {
            continue;
        }
        let module = file.to_ascii_lowercase();
        let text = jar.text(&name)?;
        let mut s = format!(
            "//! Generated by `cargo xtask {}` from {} (l10n/{file}.kt): do not edit.\n\nuse super::Translation;\n",
            spec.task, spec.file_source
        );
        let mut current: Option<(String, Vec<Option<String>>)> = None;
        let mut finish = |s: &mut String, current: Option<(String, Vec<Option<String>>)>| {
            if let Some((function, texts)) = current {
                let constant = snake(&function).to_ascii_uppercase();
                let _ = writeln!(s, "\n/// Compose's `Translations.{function}()`.");
                let _ = writeln!(s, "pub(super) const {constant}: Translation = [");
                for (k, t) in texts.iter().enumerate() {
                    match t {
                        Some(t) => {
                            let _ = writeln!(s, "    Some(\"{}\"), // {}", rust_escape(t), ids[k].0);
                        }
                        None => {
                            let _ = writeln!(s, "    None, // {}", ids[k].0);
                        }
                    }
                }
                s.push_str("];\n");
                functions.insert(function, format!("{}::{constant}", ident(&module)));
            }
        };
        for line in text.lines() {
            let l = line.trim();
            if let Some(rest) = l.strip_prefix("internal fun Translations.") {
                finish(&mut s, current.take());
                let function = rest.split('(').next().unwrap_or("").trim_matches('`').to_string();
                current = Some((function, vec![None; count]));
            } else if let Some(rest) = l.strip_prefix("Strings.")
                && let Some((key, value)) = rest.split_once(" to ")
            {
                let (_, texts) = current.as_mut().ok_or(format!("{name}: a text outside a translation"))?;
                let id = ids.iter().position(|(n, _)| n == key).ok_or(format!("{name}: no Strings.{key}"))?;
                let literal = value.trim().trim_end_matches(',');
                texts[id] = Some(kotlin_string(literal).map_err(|e| format!("{name}: {e}"))?);
            }
        }
        finish(&mut s, current.take());
        out.insert(format!("{module}.rs"), s);
    }
    // mod.rs: the ids, the modules, translation_for.
    let mut m = format!(
        "//! {} in the languages Compose for desktop translates them to: generated by `cargo xtask {}`\n//! from {}, \
         do not edit.\n\nuse super::strings::Strings;\n\n/// A translation: the texts by [`Strings`]' id (Compose's \
         `Translation`, a map of them).\npub(crate) type Translation = [Option<&'static str>; {count}];\n\nimpl \
         Strings {{\n",
        spec.what, spec.task, spec.module_source
    );
    for (name, id) in &ids {
        let _ = writeln!(m, "    pub(crate) const {name}: Strings = Strings({id});");
    }
    m.push_str("}\n\n");
    let mut modules: Vec<&String> = out.keys().collect();
    modules.sort();
    for module in &modules {
        let _ = writeln!(m, "#[rustfmt::skip]\nmod {};", ident(module.trim_end_matches(".rs")));
    }
    m.push_str(
        "\n/// The translation of a locale tag (Compose's internal format: `\"\"`, `\"tr\"`, `\"pt_BR\"`; Compose's \
         `translationFor`).\npub(crate) fn translation_for(locale_tag: &str) -> Option<&'static Translation> {\n    \
         match locale_tag {\n",
    );
    for (tag, function) in &tags {
        let path = functions.get(function).ok_or(format!("no translation Translations.{function}"))?;
        let _ = writeln!(m, "        \"{tag}\" => Some(&{path}),");
    }
    m.push_str("        _ => None,\n    }\n}\n");
    out.insert("mod.rs".to_string(), m);
    Ok(out)
}

/// A Kotlin string literal's text (`"a \"b\" %1\$s"`).
fn kotlin_string(literal: &str) -> Result<String, String> {
    let inner = literal
        .strip_prefix('"')
        .and_then(|l| l.strip_suffix('"'))
        .ok_or(format!("not a string literal: {literal}"))?;
    let mut out = String::new();
    let mut chars = inner.chars();
    while let Some(c) = chars.next() {
        if c == '$' {
            return Err(format!("a template in {literal}"));
        }
        if c != '\\' {
            out.push(c);
            continue;
        }
        match chars.next() {
            Some('n') => out.push('\n'),
            Some('t') => out.push('\t'),
            Some('r') => out.push('\r'),
            Some('b') => out.push('\u{8}'),
            Some('u') => {
                let hex: String = chars.by_ref().take(4).collect();
                let v = u32::from_str_radix(&hex, 16).map_err(|_| format!("\\u{hex} in {literal}"))?;
                out.push(char::from_u32(v).ok_or(format!("\\u{hex} in {literal}"))?);
            }
            Some(c @ ('"' | '\'' | '\\' | '$')) => out.push(c),
            other => return Err(format!("an escape \\{other:?} in {literal}")),
        }
    }
    Ok(out)
}

/// A module name as Rust writes it (a keyword raw: `r#as`, `r#in`).
fn ident(name: &str) -> String {
    const KEYWORDS: [&str; 6] = ["as", "in", "fn", "if", "do", "mod"];
    if KEYWORDS.contains(&name) { format!("r#{name}") } else { name.to_string() }
}

/// A text as a Rust string literal's inside.
fn rust_escape(t: &str) -> String {
    t.chars()
        .map(|c| match c {
            '"' => "\\\"".to_string(),
            '\\' => "\\\\".to_string(),
            '\n' => "\\n".to_string(),
            '\t' => "\\t".to_string(),
            '\r' => "\\r".to_string(),
            // (controls, and what rustc and clippy won't have written as itself: bidi controls, invisible ones)
            c if c.is_control()
                || matches!(c, '\u{200b}'..='\u{200f}' | '\u{202a}'..='\u{202e}' | '\u{2060}'..='\u{2069}')
                || matches!(c, '\u{ad}' | '\u{feff}') =>
            {
                format!("\\u{{{:x}}}", c as u32)
            }
            c => c.to_string(),
        })
        .collect()
}
